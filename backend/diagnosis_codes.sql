-- Diagnosis Codes Table (ICD-10 based)
-- Run this file to add diagnosis codes support to the hospital system

-- Create diagnosis codes table
CREATE TABLE IF NOT EXISTS diagnosis_codes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE,
  description TEXT NOT NULL,
  category VARCHAR(100),
  is_common BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_code (code),
  INDEX idx_description (description(100)),
  INDEX idx_is_common (is_common),
  FULLTEXT idx_search (code, description)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Create prescription diagnoses junction table for multiple diagnoses
CREATE TABLE IF NOT EXISTS prescription_diagnoses (
  id INT AUTO_INCREMENT PRIMARY KEY,
  prescription_id INT NOT NULL,
  diagnosis_code_id INT NULL,
  custom_diagnosis TEXT NULL,
  is_primary BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (prescription_id) REFERENCES prescriptions(id) ON DELETE CASCADE,
  FOREIGN KEY (diagnosis_code_id) REFERENCES diagnosis_codes(id) ON DELETE SET NULL,
  INDEX idx_prescription_id (prescription_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

